// 多行文本（课程介绍 / 个人简介 / 驳回原因等）的展示规范化。
//
// 这些字段由教师或管理员在 textarea 里自由输入，实际数据里常见的换行写法有：
//   - Windows 回车换行 "\r\n"、老式 Mac 回车 "\r"、以及 Unicode 行分隔符
//   - 连续多个换行（敲了 3~5 个回车）造成的多余空行
//   - 换行前后带的空格/制表符（" \n " 这种看不见的空白）
//
// 小程序 <text> 用 white-space: pre-wrap 渲染，换行会原样输出：连续空行会撑出
// 大段空白，而 " \n " 这类带空白的换行又会让段落看起来忽宽忽窄。这里统一成
// 「段落之间恰好一个空行」的格式，语义不变，只调整换行展示。
//
// 约定：
//   - 单个换行 = 段内换行，保留
//   - 两个及以上换行 = 段落分隔，统一压缩为一个空行（即 "\n\n"）
//   - 行首行尾空白（含全角空格）去掉
//   - 首尾空行去掉
const normalizeMultiline = (value) => {
  if (value == null) return '';
  return String(value)
    // 统一换行符：\r\n / \r / \u2028 / \u2029 -> \n
    .replace(/\r\n?/g, '\n')
    .replace(/[\u2028\u2029]/g, '\n')
    // 去掉每行首尾的空白（含全角空格、制表符），避免出现「看不见的空行」
    .split('\n')
    .map((line) => line.replace(/^[\s\u3000]+|[\s\u3000]+$/g, ''))
    .join('\n')
    // 3 个及以上换行（即 2 个以上空行）压缩为段落分隔
    .replace(/\n{3,}/g, '\n\n')
    // 去掉首尾空行
    .replace(/^\n+|\n+$/g, '');
};

module.exports = { normalizeMultiline };
